#!/usr/bin/env node

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const API_ROOT = 'https://cms.o9solutions.com/wp-json/wp/v2';
const COLLECTIONS = [
  { endpoint: 'posts', sourceType: 'post', type: 'Blog', path: 'articles' },
  { endpoint: 'resource', sourceType: 'resource', type: 'Research', path: 'resources' }
];

function optionValues(name) {
  return process.argv.flatMap((argument, index) => (
    argument === name && process.argv[index + 1] ? [process.argv[index + 1]] : []
  ));
}

function optionValue(name, fallback) {
  const index = process.argv.indexOf(name);
  return index >= 0 && process.argv[index + 1] ? process.argv[index + 1] : fallback;
}

function decodeEntities(value) {
  return String(value || '')
    .replace(/&#(\d+);/g, (_, code) => String.fromCodePoint(Number(code)))
    .replace(/&#x([\da-f]+);/gi, (_, code) => String.fromCodePoint(Number.parseInt(code, 16)))
    .replaceAll('&amp;', '&')
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
    .replaceAll('&quot;', '"')
    .replaceAll('&#039;', "'")
    .replaceAll('&nbsp;', ' ');
}

function cleanText(value) {
  return decodeEntities(String(value || '').replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ').trim();
}

const neurosymbolicPattern = /\b(?:neuro[\s-]?symbolic|neural[\s-]+symbolic|nesy)\b/i;

export function normalizeO9Record(record, collection) {
  const path = String(new URL(record.link).pathname).replace(/^\/(?:br|cn|tw|ja|ko)\//, '/');
  if (!path.startsWith(`/${collection.path}/`)) return null;
  const title = cleanText(record.title?.rendered);
  const excerpt = cleanText(record.excerpt?.rendered);
  const content = cleanText(record.content?.rendered);
  return {
    title,
    excerpt,
    neurosymbolicMatch: neurosymbolicPattern.test(`${title} ${content || excerpt}`),
    date: String(record.date || '').slice(0, 10),
    url: `https://o9solutions.com${path.replace(/\/$/, '')}`,
    type: collection.type,
    sourceType: collection.sourceType,
    sourceId: Number(record.id) || 0
  };
}

export function buildO9Snapshot(recordsByType, generatedAt = new Date().toISOString()) {
  const posts = COLLECTIONS.flatMap((collection) => (
    (recordsByType[collection.sourceType] || [])
      .map((record) => normalizeO9Record(record, collection))
      .filter((record) => record?.title && record.date && record.url)
  ));
  const deduplicated = [...new Map(posts.map((post) => [post.url, post])).values()]
    .sort((left, right) => right.date.localeCompare(left.date) || left.title.localeCompare(right.title));
  return {
    generatedAt,
    sources: {
      post: 'https://o9solutions.com/resources?type=post',
      resource: 'https://o9solutions.com/resources?type=resource'
    },
    counts: {
      post: deduplicated.filter((post) => post.sourceType === 'post').length,
      resource: deduplicated.filter((post) => post.sourceType === 'resource').length,
      total: deduplicated.length
    },
    posts: deduplicated
  };
}

async function fetchCollection(collection) {
  const records = [];
  let page = 1;
  let totalPages = 1;
  do {
    const fields = 'id,slug,link,date,modified,title,excerpt,content';
    const url = `${API_ROOT}/${collection.endpoint}?per_page=100&page=${page}&lang=en&_fields=${fields}`;
    const response = await fetch(url, { headers: { 'User-Agent': 'NeSy-Atlas/1.0' } });
    if (!response.ok) throw new Error(`o9 ${collection.sourceType} page ${page}: HTTP ${response.status}`);
    totalPages = Number(response.headers.get('x-wp-totalpages')) || 1;
    records.push(...await response.json());
    page += 1;
  } while (page <= totalPages);
  return records;
}

async function readInputs(paths) {
  const pages = await Promise.all(paths.map(async (path) => JSON.parse(await readFile(resolve(path), 'utf8'))));
  return pages.flat();
}

function dataScript(snapshot) {
  return `// Generated by scripts/update-o9-posts.mjs. Do not edit manually.\n`
    + `globalThis.O9_POSTS_META = ${JSON.stringify({
      generatedAt: snapshot.generatedAt,
      sources: snapshot.sources,
      counts: snapshot.counts
    }, null, 2)};\n`
    + `globalThis.O9_POSTS = ${JSON.stringify(snapshot.posts, null, 2)};\n`;
}

async function main() {
  const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const postInputs = optionValues('--post-input');
  const resourceInputs = optionValues('--resource-input');
  const recordsByType = {
    post: postInputs.length ? await readInputs(postInputs) : await fetchCollection(COLLECTIONS[0]),
    resource: resourceInputs.length ? await readInputs(resourceInputs) : await fetchCollection(COLLECTIONS[1])
  };
  const snapshot = buildO9Snapshot(recordsByType);
  const jsonPath = resolve(optionValue('--output-json', resolve(projectRoot, 'data/o9-posts.json')));
  const scriptPath = resolve(optionValue('--output-script', resolve(projectRoot, 'data/o9-posts.js')));
  await mkdir(dirname(jsonPath), { recursive: true });
  await mkdir(dirname(scriptPath), { recursive: true });
  await writeFile(jsonPath, `${JSON.stringify(snapshot, null, 2)}\n`, 'utf8');
  await writeFile(scriptPath, dataScript(snapshot), 'utf8');
  console.log(`Wrote ${snapshot.counts.post} o9 posts and ${snapshot.counts.resource} resources`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
